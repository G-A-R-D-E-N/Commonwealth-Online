		assert(maximum && DecodeTransaction(*maximum, 1).status == DecodeStatus::Committed);
		assert(!EncodeTransaction(1, nlohmann::json{ { "data", std::string(MaximumTransactionBytes - emptyBody.size() + 1, 'x') } }));
