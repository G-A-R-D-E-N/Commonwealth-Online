		assert(DecodeTransaction(rawFrame("{\"sequence\":1,\"payload\":[]}"), 1).status == DecodeStatus::Invalid);
		assert(DecodeTransaction(rawFrame("{\"sequence\":\"1\",\"payload\":{}}"), 1).status == DecodeStatus::Invalid);
