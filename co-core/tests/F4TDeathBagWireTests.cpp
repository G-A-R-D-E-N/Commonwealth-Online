		assert(parsedFirst.payload.at("operation") == "first");
		const auto parsedSecond = DecodeTransaction(std::string_view(stream).substr(parsedFirst.consumed), 2);
		assert(parsedSecond.status == DecodeStatus::Committed && parsedSecond.payload.at("operation") == "second");
		assert(DecodeTransaction(std::string_view(*second).substr(0, second->size() - 1), 2).status == DecodeStatus::Incomplete);
