local co_core_dir = os.scriptdir()

if os.projectdir() == co_core_dir then
    set_project("CommonwealthOnlineCore")
    set_version("0.1.0")
    set_languages("c++23")
    set_policy("build.intermediate_directory", false)
    set_targetdir("$(builddir)/$(plat)/$(arch)/$(mode)")
    set_warnings("allextra")
    add_rules("mode.debug", "mode.release", "mode.releasedbg")
    if is_plat("linux") then
        -- Sanitizer lanes need a toolchain whose runtime is installed;
        -- CO_TOOLCHAIN lets CI pick gcc without changing the default build.
        set_toolchains(os.getenv("CO_TOOLCHAIN") or "clang")
    end
end

local core_target_index = 0
function core_target(name, basename)
    core_target_index = core_target_index + 1
    target(name)
    set_objectdir(path.join("build", ".o", tostring(core_target_index)))
    if basename then
        set_basename(basename)
    end
end

-- Constraint: test targets keep add_undefines("NDEBUG"); the suites use bare assert.
function core_test(name, basename, ...)
    core_target(name, basename)
        set_kind("binary")
        add_deps("CommonwealthOnlineCore")
        for _, file in ipairs({...}) do
            add_files(path.join(co_core_dir, "tests/" .. file))
        end
        add_forceincludes("F4TAssertionsEnabled.h")
        add_undefines("NDEBUG")
        add_tests("default")
    target_end()
end

