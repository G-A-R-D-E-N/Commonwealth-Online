const fs = require("fs");
const os = require("os");
const path = require("path");
const assert = require("assert");

const hook = path.join(__dirname, "commit-msg");
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "commitmsg-"));
const run = (msg) => {
  const file = path.join(dir, "msg.txt");
  fs.writeFileSync(file, msg);
  return spawnSync(process.execPath, [hook, file], { encoding: "utf8" }).status;
};

